#!/usr/bin/env python3
"""Generate SNI tray icons to include/scran-pixmap.h and src/scran-pixmap.c.

Usage (from the repository root):
    python3 assets/generate_pixmaps.py
With deps (nix):
    nix shell nixpkgs#python3 nixpkgs#resvg nixpkgs#ffmpeg-headless -c python3 assets/generate_pixmaps.py
"""

import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from textwrap import dedent


REPO_ROOT = Path(__file__).resolve().parent.parent

DIMENSIONS = (16, 22, 24, 32, 48, 64)

ICONS = {
    "lime":       "assets/scran-citrus-lime.svg",
    "grapefruit": "assets/scran-citrus-grapefruit.svg",
}


def rasterize_svg(path: Path, dimension: int) -> bytes:
    png_bytes = subprocess.check_output(
        [
            "resvg",
            "-w", str(dimension),
            "-h", str(dimension),
            str(path),
            "-c",
        ]
    )

    # StatusNotifierItem IconPixmap requires non-premultiplied ARGB32 in
    # network byte order (big-endian): A, R, G, B bytes, regardless of host
    # endianness.
    pixmap_bytes = subprocess.check_output(
        [
            "ffmpeg",
            "-v", "error",
            "-f", "png_pipe",
            "-i", "-",
            "-f", "rawvideo",
            "-pix_fmt", "argb",
            "-",
        ],
        input=png_bytes,
    )
    assert len(pixmap_bytes) == 4 * dimension * dimension

    return pixmap_bytes


def generate_c_header() -> str:
    declarations = "\n".join(
        f"extern const struct StatusNotifierItem_icon_pixmap scran_pixmaps_{icon_name}[{len(DIMENSIONS)}];"
        for icon_name in ICONS
    )

    return dedent(
        """\
        // Generated by assets/generate_pixmaps.py. Do not edit by hand.

        #ifndef SCRAN_PIXMAP_H
        #define SCRAN_PIXMAP_H

        #include <stddef.h>
        #include <stdint.h>


        // StatusNotifierItem IconPixmap icon.
        struct StatusNotifierItem_icon_pixmap {{
            int  width;
            int  height;
            size_t _data_size;
            const uint8_t *data; // non-premultiplied ARGB32, network byte order (big-endian).
        }};

        {declarations}


        #endif
        """
    ).format(declarations=declarations)


def generate_c_source() -> str:
    parts = [
        dedent(
            """\
            // Generated by assets/generate_pixmaps.py. Do not edit by hand.
            //
            // StatusNotifierItem IconPixmap format: non-premultiplied ARGB32, network byte order (big-endian).
            // Rasterized with resvg.

            #include <stdint.h>
            #include "scran-pixmap.h"
            """
        )
    ]

    for icon_name, svg_path in ICONS.items():
        parts.append(f"\n// {icon_name}: {svg_path}\n")
        pixmap_instances = []

        for dimension in DIMENSIONS:
            pixmap_bytes = rasterize_svg(REPO_ROOT / svg_path, dimension)
            pixmap_byte_array_name = f"scran_pixmap_{icon_name}_{dimension}"
            pixmap_byte_array_rows = []
            for offset in range(0, len(pixmap_bytes), 16):
                row = ", ".join(f"0x{byte:02x}" for byte in pixmap_bytes[offset : offset + 16])
                pixmap_byte_array_rows.append(f"  {row}")

            parts.append(
                dedent(
                    """
                    static const uint8_t {array_name}[{byte_count}] = {{
                    {array_contents}
                    }};
                    """
                ).format(
                    array_name=pixmap_byte_array_name,
                    byte_count=len(pixmap_bytes),
                    array_contents=",\n".join(pixmap_byte_array_rows),
                )
            )

            pixmap_instances.append(
                "    {\n"
                f"        .width = {dimension},\n"
                f"        .height = {dimension},\n"
                f"        ._data_size = sizeof({pixmap_byte_array_name}),\n"
                f"        .data = {pixmap_byte_array_name}\n"
                "    },"
            )

        parts.append(
            dedent(
                """
                const struct StatusNotifierItem_icon_pixmap scran_pixmaps_{icon_name}[] = {{
                {instances}
                }};
                """
            ).format(
                icon_name=icon_name,
                instances="\n".join(pixmap_instances),
            )
        )

    return "".join(parts)


def write_generated_file(filename: str, contents: str) -> None:
    # Write to a temp file first in case anything errors, so we don't update the
    # pre-existing file with junk.
    with TemporaryDirectory(prefix=".generate-pixmaps-", dir=REPO_ROOT) as tmpdir:
        tmppath = Path(tmpdir) / Path(filename).name
        tmppath.write_text(contents, encoding="ascii")
        tmppath.replace(REPO_ROOT / filename)
        print(f"Wrote {filename}", file=sys.stderr)


def main() -> None:
    header = generate_c_header()
    source = generate_c_source()

    write_generated_file("include/scran-pixmap.h", header)
    write_generated_file("src/scran-pixmap.c", source)


if __name__ == "__main__":
    main()
